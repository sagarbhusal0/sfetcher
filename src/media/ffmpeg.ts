import { FFmpeg } from '@ffmpeg/ffmpeg';

let ffmpeg: FFmpeg | null = null;
let loading: Promise<FFmpeg> | null = null;

/** Multicast log listeners (singleton FFmpeg is shared across jobs). */
const logListeners = new Set<(message: string) => void>();
let logForwarding = false;

/**
 * Subscribe to FFmpeg stderr/stdout lines. Returns an unsubscribe function.
 * Safe to call before load; delivery starts once the instance exists.
 */
export function onFFmpegLog(listener: (message: string) => void): () => void {
  logListeners.add(listener);
  return () => {
    logListeners.delete(listener);
  };
}

/**
 * Test-only fan-out trigger (the production trigger is the FFmpeg
 * instance's `log` event after load). Lets unit tests exercise tape
 * mechanics without booting WASM.
 */
export function __emitFFmpegLogForTests(message: string): void {
  for (const l of [...logListeners]) l(message);
}

/**
 * Collect the last `keep` log lines during one mux. Attach inside the mux
 * lock and read `.tail()` when a step fails — this is what turns a bare
 * "exit 1" into the actual ffmpeg diagnosis.
 */
export function createLogTape(keep = 40): { tail: () => string; dispose: () => void } {
  const lines: string[] = [];
  const off = onFFmpegLog((message) => {
    lines.push(message);
    if (lines.length > keep) lines.shift();
  });
  return {
    tail: () => lines.slice(-keep).join('\n').slice(-2000),
    dispose: off,
  };
}

/**
 * Load the locally bundled, single-threaded ffmpeg core.
 * Single-threaded on purpose: no SharedArrayBuffer / COOP-COEP requirement,
 * which extension pages cannot guarantee. Everything runs from
 * chrome-extension:// URLs — nothing is fetched from a remote server.
 */
export function loadFFmpeg(onLog?: (message: string) => void): Promise<FFmpeg> {
  if (ffmpeg) return Promise.resolve(ffmpeg);
  if (loading) return loading;
  loading = (async () => {
    const ff = new FFmpeg();
    if (onLog) ff.on('log', ({ message }) => onLog(message));
    await ff.load({
      coreURL: chrome.runtime.getURL('/ffmpeg/ffmpeg-core.js'),
      wasmURL: chrome.runtime.getURL('/ffmpeg/ffmpeg-core.wasm'),
    });
    ffmpeg = ff;
    if (!logForwarding) {
      logForwarding = true;
      ff.on('log', ({ message }) => {
        for (const l of [...logListeners]) {
          try {
            l(message);
          } catch {
            // never break the mux on a logging failure
          }
        }
      });
    }
    return ff;
  })().catch((e) => {
    loading = null;
    throw e;
  });
  return loading;
}

export interface RemuxInput {
  /** MEMFS-safe filename generated by the caller (never user input). */
  name: string;
  data: Uint8Array;
}

/**
 * Remux already-downloaded segments into an MP4 via stream copy (no
 * transcoding). Returns the output bytes. Throws with the ffmpeg stderr tail
 * when the combination is unsupported — callers surface that honestly.
 */
export async function remuxToMp4(
  ff: FFmpeg,
  inputs: RemuxInput[],
  strategy: 'concat-demuxer' | 'concat-protocol',
  outputName: string,
  onProgress?: (ratio: number) => void,
  extraOutputArgs?: string[],
): Promise<Uint8Array> {
  if (inputs.length === 0) throw new Error('No segments to remux');
  const off = onProgress ? ff.on('progress', ({ progress }) => onProgress(progress)) : null;
  try {
    for (const input of inputs) {
      await ff.writeFile(input.name, input.data);
    }
    let args: string[];
    if (strategy === 'concat-demuxer') {
      // MPEG-TS segments: concat demuxer handles timestamps correctly.
      const list = inputs.map((i) => `file '${i.name}'`).join('\n');
      await ff.writeFile('list.txt', new TextEncoder().encode(list));
      args = ['-f', 'concat', '-safe', '0', '-i', 'list.txt', '-c', 'copy', ...(extraOutputArgs ?? []), outputName];
    } else {
      // Fragmented MP4 (init segment first): byte-level concat protocol.
      args = ['-i', `concat:${inputs.map((i) => i.name).join('|')}`, '-c', 'copy', ...(extraOutputArgs ?? []), outputName];
    }
    const code = await ff.exec(args);
    if (code !== 0) {
      throw new Error(`ffmpeg remux failed (exit ${code}): unsupported stream combination`);
    }
    const data = (await ff.readFile(outputName)) as Uint8Array;
    return data.slice();
  } finally {
    if (off) ff.off('progress', off as (...args: unknown[]) => void);
    for (const input of inputs) {
      await ff.deleteFile(input.name).catch(() => undefined);
    }
    await ff.deleteFile('list.txt').catch(() => undefined);
    await ff.deleteFile(outputName).catch(() => undefined);
  }
}

/**
 * Package separate full-track files (e.g. DASH video+audio) into one MP4.
 */
export async function packageTracks(
  ff: FFmpeg,
  tracks: RemuxInput[],
  outputName: string,
  onProgress?: (ratio: number) => void,
): Promise<Uint8Array> {
  if (tracks.length === 0) throw new Error('No tracks to package');
  const off = onProgress ? ff.on('progress', ({ progress }) => onProgress(progress)) : null;
  try {
    for (const t of tracks) {
      await ff.writeFile(t.name, t.data);
    }
    const args: string[] = [];
    for (const t of tracks) args.push('-i', t.name);
    args.push('-c', 'copy', '-movflags', '+faststart', outputName);
    const code = await ff.exec(args);
    if (code !== 0) {
      throw new Error(`ffmpeg packaging failed (exit ${code}): unsupported codec combination`);
    }
    const data = (await ff.readFile(outputName)) as Uint8Array;
    return data.slice();
  } finally {
    if (off) ff.off('progress', off as (...args: unknown[]) => void);
    for (const t of tracks) {
      await ff.deleteFile(t.name).catch(() => undefined);
    }
    await ff.deleteFile(outputName).catch(() => undefined);
  }
}
